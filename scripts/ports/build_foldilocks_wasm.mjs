// Builds native/foldilocks-wasm (SIMD matrix-vector kernel) and embeds it as
// src/bots/agents/foldilocks/kernel.ts. Usage: node scripts/ports/build_foldilocks_wasm.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const crate = path.join(root, 'native/foldilocks-wasm');
execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: 'inherit',
  env: { ...process.env, RUSTFLAGS: '-C target-feature=+simd128' },
});
const wasm = readFileSync(path.join(crate, 'target/wasm32-unknown-unknown/release/foldilocks_wasm.wasm'));
writeFileSync(
  path.join(root, 'src/bots/agents/foldilocks/kernel.ts'),
  `// Generated by scripts/ports/build_foldilocks_wasm.mjs from native/foldilocks-wasm. Do not edit.\n` +
    `export const KERNEL_WASM = '${wasm.toString('base64')}';\n`,
);
console.log(`kernel.ts: ${wasm.length} bytes of wasm`);
