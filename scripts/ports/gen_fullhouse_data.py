"""Extracts fullhouse-bot's runtime data into src/bots/agents/foldilocks/data.ts, unchanged:
Deep CFR network weights (float32, base64), preflop equity tables and the push/fold sets.
Usage: bot-assets/venv/bin/python -I scripts/ports/gen_fullhouse_data.py <external/fullhouse-bot> <out.ts>"""
import base64, json, sys
from pathlib import Path
import numpy as np

repo, out = Path(sys.argv[1]), Path(sys.argv[2])
sys.path.insert(0, str(repo))
from bot import bot as fh  # noqa: E402

model = np.load(repo / "data" / "deep_cfr_model.npz")
weights = {k: {"shape": list(model[k].shape), "data": base64.b64encode(np.ascontiguousarray(model[k], dtype="<f4").tobytes()).decode()} for k in model.files}
eq = np.load(repo / "data" / "preflop_equity.npz")
equity = {k: {"shape": list(eq[k].shape), "data": base64.b64encode(np.ascontiguousarray(eq[k], dtype="<f4").tobytes()).decode(), "dtype": str(eq[k].dtype)} for k in eq.files}
sets = {n: sorted(getattr(fh, n)) for n in ("_PF_TIER1", "_PF_TIER2", "_PF_TIER3", "_PF_CALL_TIGHT", "_PF_CALL_MEDIUM", "_PF_CALL_WIDE")}
out.write_text(
    "// Generated by scripts/ports/gen_fullhouse_data.py from external/fullhouse-bot (MIT, Advit Arora). Do not edit.\n"
    "/* eslint-disable */\n"
    f"export const WEIGHTS: Record<string, {{ shape: number[]; data: string }}> = {json.dumps(weights)};\n"
    f"export const EQUITY: Record<string, {{ shape: number[]; data: string; dtype: string }}> = {json.dumps(equity)};\n"
    f"export const RANGES: Record<string, string[]> = {json.dumps(sets)};\n"
)
print("wrote", out, out.stat().st_size, "bytes;", {k: v["dtype"] for k, v in equity.items()})
