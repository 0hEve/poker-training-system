"""Extracts poker_sequoia's gto_upload tables and tuning constants into
src/bots/agents/sequoia/data.ts, unchanged.
Usage: bot-assets/venv/bin/python -I scripts/ports/gen_sequoia_data.py <external/poker-sequoia> <out.ts>"""
import importlib.util, json, sys
from pathlib import Path

repo, out = Path(sys.argv[1]), Path(sys.argv[2])
spec = importlib.util.spec_from_file_location("gto_upload", repo / "bots" / "gto_upload" / "agent.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
data = {
    "PRE": {k: list(v) for k, v in m.PRE.items()},
    "RANGE_EQ": {k: list(v) for k, v in m.RANGE_EQ.items()},
    "RANGE_PCTS": list(m.RANGE_PCTS),
    "SCORE_QUANTILES": list(m.SCORE_QUANTILES),
    "K": m.K, "OPEN_W": m.OPEN_W, "POS_SHOVE": m.POS_SHOVE, "PUSH_W": m.PUSH_W,
    "EQ_F": list(m.EQ_F), "EQ_T": list(m.EQ_T), "EQ_R": list(m.EQ_R),
    "DRAW_EQ": {k: list(v) for k, v in m.DRAW_EQ.items()},
    "NSEATS": m.NSEATS, "NC": m.NC, "PRIOR_W": m.PRIOR_W, "REC_VERSION": m.REC_VERSION,
}
lines = ["// Generated by scripts/ports/gen_sequoia_data.py from external/poker-sequoia bots/gto_upload/agent.py. Do not edit.", "/* eslint-disable */"]
for k, v in data.items():
    lines.append(f"export const {k} = {json.dumps(v)} as const;")
out.write_text("\n".join(lines) + "\n")
print("wrote", out, out.stat().st_size, "bytes")
