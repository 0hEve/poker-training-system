/// <reference types="node" />

import { writeFile } from 'node:fs/promises';
import { addCard, evalWith2, newAcc, resetAcc } from '../../../sim/eval';
import { rngFor } from '../../../sim/rng';
import { CLASS, CLASSES, COMBOS, FIRST, SECOND, MASK_LO, MASK_HI } from './cards';
import { EQUITY_PROFILES } from './charts';
import { MAX_DEPTH, MIN_DEPTH, solveBlinds } from './solve-blinds';

const TRIALS = 65536;
const SEED = 17205;

export async function generate(path: string) {
  const columns = EQUITY_PROFILES.length;
  const values = Buffer.alloc(169 * columns * 2);
  const cdf = new Float64Array(COMBOS);
  const board = newAcc();
  for (let id = 0; id < 169; id++) {
    const combo = CLASSES[id][0];
    const a = FIRST[combo];
    const b = SECOND[combo];
    const heroLo = MASK_LO[a] | MASK_LO[b];
    const heroHi = MASK_HI[a] | MASK_HI[b];
    for (let profile = 0; profile < columns; profile++) {
      const rnd = rngFor(SEED, id * columns + profile);
      const weights = EQUITY_PROFILES[profile];
      let mass = 0;
      for (let c = 0; c < COMBOS; c++) {
        const x = FIRST[c];
        const y = SECOND[c];
        if (!(heroLo & (MASK_LO[x] | MASK_LO[y])) && !(heroHi & (MASK_HI[x] | MASK_HI[y]))) {
          mass += weights[CLASS[c]];
        }
        cdf[c] = mass;
      }
      let halfWins = 0;
      for (let trial = 0; trial < TRIALS; trial++) {
        const target = rnd() * mass;
        let lo = 0;
        let hi = COMBOS - 1;
        while (lo < hi) {
          const mid = (lo + hi) >> 1;
          if (cdf[mid] > target) hi = mid;
          else lo = mid + 1;
        }
        const x = FIRST[lo];
        const y = SECOND[lo];
        let usedLo = heroLo | MASK_LO[x] | MASK_LO[y];
        let usedHi = heroHi | MASK_HI[x] | MASK_HI[y];
        resetAcc(board);
        for (let k = 0; k < 5; k++) {
          let card: number;
          do card = (rnd() * 52) | 0;
          while ((usedLo & MASK_LO[card]) || (usedHi & MASK_HI[card]));
          usedLo |= MASK_LO[card];
          usedHi |= MASK_HI[card];
          addCard(board, card);
        }
        const hero = evalWith2(board, a, b);
        const villain = evalWith2(board, x, y);
        halfWins += hero > villain ? 2 : hero === villain ? 1 : 0;
      }
      values.writeUInt16LE(Math.round(65535 * halfWins / (2 * TRIALS)), 2 * (id * columns + profile));
    }
  }
  const asSource = (bytes: Buffer) => bytes.toString('base64').match(/.{1,100}/g)!
    .map((row) => `  '${row}'`).join(' +\n') + ';\n';
  const blinds = Buffer.from(solveBlinds());
  await writeFile(path, `// Generated by offline.mjs generate. ${TRIALS} deals per class/profile, seed ${SEED}.\n`
    + `export const EQUITY_COLUMNS = ${columns};\nexport const EQUITY_BASE64 =\n` + asSource(values)
    + `export const MIN_DEPTH = ${MIN_DEPTH};\nexport const MAX_DEPTH = ${MAX_DEPTH};\nexport const BLINDS_BASE64 =\n` + asSource(blinds));
}
