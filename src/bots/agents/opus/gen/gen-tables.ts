/// <reference types="node" />
/**
 * Offline generator for the preflop tables (run: node src/bots/agents/opus/gen/run.mjs).
 * - HU[i*169+j]: equity (win + tie/2) of class i vs class j, Monte Carlo with card removal.
 * - VSN[(n-1)*169+i]: equity of class i vs n random hands (n = 1..5).
 */
import { writeFileSync } from 'node:fs';
import { eval7 } from '../../../../sim/eval';
import { sfc32 } from '../../../../sim/rng';
import { classOf } from '../cards';

const rnd = sfc32(0x1234, 0x5678, 0x9abc, 0xdef0);
const byClass: number[][][] = Array.from({ length: 169 }, () => []);
for (let a = 0; a < 52; a++) for (let b = a + 1; b < 52; b++) byClass[classOf(a, b)].push([a, b]);

const used = new Uint8Array(52);
const seven = new Int32Array(7);
const board = new Int32Array(5);
let stamp = 0;
const usedStamp = new Uint32Array(52);
function mark(c: number) {
  usedStamp[c] = stamp;
}
const isUsed = (c: number) => usedStamp[c] === stamp;
function dealBoard() {
  for (let k = 0; k < 5; k++) {
    let c: number;
    do c = (rnd() * 52) | 0;
    while (isUsed(c));
    mark(c);
    board[k] = c;
  }
}
const score = (a: number, b: number) => {
  seven[0] = board[0]; seven[1] = board[1]; seven[2] = board[2]; seven[3] = board[3]; seven[4] = board[4];
  seven[5] = a; seven[6] = b;
  return eval7(seven, 7);
};
void used;

const SAMPLES_HU = Number(process.env.HU_SAMPLES ?? 3000);
const HU = new Uint16Array(169 * 169);
const t0 = Date.now();
for (let i = 0; i < 169; i++) {
  for (let j = i; j < 169; j++) {
    let eq = 0;
    let n = 0;
    while (n < SAMPLES_HU) {
      const h1 = byClass[i][(rnd() * byClass[i].length) | 0];
      const h2 = byClass[j][(rnd() * byClass[j].length) | 0];
      if (h1[0] === h2[0] || h1[0] === h2[1] || h1[1] === h2[0] || h1[1] === h2[1]) continue;
      stamp++;
      mark(h1[0]); mark(h1[1]); mark(h2[0]); mark(h2[1]);
      dealBoard();
      const s1 = score(h1[0], h1[1]);
      const s2 = score(h2[0], h2[1]);
      eq += s1 > s2 ? 1 : s1 === s2 ? 0.5 : 0;
      n++;
    }
    const e = eq / n;
    HU[i * 169 + j] = Math.round(e * 65535);
    HU[j * 169 + i] = Math.round((1 - e) * 65535);
  }
  if (i % 20 === 0) console.error(`HU row ${i} (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
}
for (let i = 0; i < 169; i++) HU[i * 169 + i] = 32768;

const SAMPLES_N = Number(process.env.N_SAMPLES ?? 30000);
const VSN = new Uint16Array(5 * 169);
for (let n = 1; n <= 5; n++) {
  for (let i = 0; i < 169; i++) {
    let eq = 0;
    for (let t = 0; t < SAMPLES_N; t++) {
      const h = byClass[i][(rnd() * byClass[i].length) | 0];
      stamp++;
      mark(h[0]); mark(h[1]);
      const opp: number[] = [];
      for (let k = 0; k < 2 * n; k++) {
        let c: number;
        do c = (rnd() * 52) | 0;
        while (isUsed(c));
        mark(c);
        opp.push(c);
      }
      dealBoard();
      const me = score(h[0], h[1]);
      let best = 0;
      let ties = 0;
      for (let k = 0; k < n; k++) {
        const s = score(opp[2 * k], opp[2 * k + 1]);
        if (s > best) { best = s; ties = 0; }
        if (s === best) ties++;
      }
      if (me > best) eq += 1;
      else if (me === best) eq += 1 / (ties + 1);
    }
    VSN[(n - 1) * 169 + i] = Math.round((eq / SAMPLES_N) * 65535);
  }
  console.error(`vs ${n} done`);
}

const b64 = (a: Uint16Array) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
const out = `// Generated by gen/gen-tables.ts — do not edit. HU: ${SAMPLES_HU} samples/pair, VSN: ${SAMPLES_N} samples.
export const HU_B64 = '${b64(HU)}';
export const VSN_B64 = '${b64(VSN)}';
`;
writeFileSync(`${process.env.OPUS_ROOT}/src/bots/agents/opus/tables.data.ts`, out);
console.error('wrote tables.data.ts');
